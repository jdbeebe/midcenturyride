#!/usr/bin/env python3
"""Turn assets/img/credits.json into assets/img/manifest.js (window.HOME_IMAGES).

Run from the repo root:  python3 scripts/build-manifest.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
credits = json.loads((root / "assets/img/credits.json").read_text())

images = {}
for c in credits:
    if not c.get("file"):
        continue
    if not (root / "assets/img" / c["file"]).exists():
        print(f"skip, missing file: {c['file']}")
        continue
    author = (c.get("author") or "").strip()
    lic = (c.get("license") or "").strip()
    credit = " · ".join(x for x in [author, lic] if x)
    images.setdefault(str(c["order"]), []).append({
        "src": f"assets/img/{c['file']}",
        "credit": credit,
        "source": c.get("sourceUrl", ""),
        "focus": c.get("focus", "50% 50%"),
    })

out = "// Generated by scripts/build-manifest.py from credits.json. Do not edit by hand.\nwindow.HOME_IMAGES = " + json.dumps(images, indent=1, ensure_ascii=False) + ";\n"
(root / "assets/img/manifest.js").write_text(out)
print(f"{sum(len(v) for v in images.values())} images for {len(images)} houses")
