#!/usr/bin/env python3
"""Fetch the Ride with GPS route and write data/route.js (window.ROUTE).

Run from anywhere:  python3 scripts/build-route.py [path-to-saved-route.json]
Without an argument it downloads https://ridewithgps.com/routes/54307217.json.
"""
import json, math, re, sys, urllib.request
from pathlib import Path

ROUTE_ID = 54307217
URL = f"https://ridewithgps.com/routes/{ROUTE_ID}"
root = Path(__file__).resolve().parent.parent

if len(sys.argv) > 1:
    data = json.loads(Path(sys.argv[1]).read_text())
else:
    req = urllib.request.Request(URL + ".json", headers={"User-Agent": "midcenturyride-site/0.1"})
    data = json.loads(urllib.request.urlopen(req).read())
r = data.get("route", data)

M_PER_MI, FT_PER_M = 1609.344, 3.28084
mi = lambda m: round(m / M_PER_MI, 2)

def dist(a_lat, a_lng, b_lat, b_lng):
    k = math.cos(math.radians((a_lat + b_lat) / 2))
    return math.hypot((a_lat - b_lat) * 111_320, (a_lng - b_lng) * 111_320 * k)

track = r["track_points"]

def locate(lat, lng, start):
    """Earliest pass along the track (from `start`) that comes within ~40 m of the best pass."""
    ds = [(dist(lat, lng, p["y"], p["x"]), i) for i, p in enumerate(track) if i >= start]
    best = min(d for d, _ in ds)
    for d, i in ds:
        if d <= best + 40:
            return i, d

def tidy_cue(text):
    t = (text.replace("Turn ", "").replace("Make a ", "")
            .replace("Continue onto", "Straight onto").strip())
    return t[:1].upper() + t[1:]

houses, extras, prev = {}, [], 0
pois = sorted(r["points_of_interest"], key=lambda p: int(m.group(1)) if (m := re.match(r"\s*(\d+)\)", p["description"] or "")) else 999)
for p in pois:
    desc = p.get("description") or ""
    lat, lng = float(p["lat"]), float(p["lng"])
    m = re.match(r"\s*(\d+)\)", desc)
    if not m:
        extras.append({"name": p["name"].strip(), "lat": round(lat, 5), "lng": round(lng, 5),
                       "note": " ".join(desc.split())})
        continue
    order = int(m.group(1))
    tag = re.search(r"\[(.*?)\]", desc)
    tag = tag.group(1).strip() if tag else ""
    idx, off = locate(lat, lng, prev)
    prev = idx
    houses[order] = {
        "lat": round(lat, 5), "lng": round(lng, 5),
        "mile": mi(track[idx]["d"]),
        "ti": idx,
        "routeName": p["name"].strip(),
        "visit": ("Stop" if tag.lower().startswith("stop") else "Ride by" if tag else None),
        "stopAt": (tag[len("stop on "):].strip() if tag.lower().startswith("stop on ") else None),
        "offRouteM": round(off),
    }

# Turn-by-turn cues, attached to the leg that leads *to* each house.
cues = [{"mile": mi(c["d"]), "turn": c.get("t", ""), "text": tidy_cue(c.get("n", ""))} for c in r["course_points"]]
miles = [(o, h["mile"]) for o, h in sorted(houses.items())]
for k, (o, m_here) in enumerate(miles):
    m_prev = miles[k - 1][1] if k else -1
    houses[o]["cuesIn"] = [c for c in cues if m_prev < c["mile"] <= m_here]
finish = [c for c in cues if c["mile"] > miles[-1][1]]

route = {
    "id": ROUTE_ID,
    "url": URL,
    "name": r["name"].strip(),
    "reference": {"label": "New Canaan Mid-Century Modern survey (USModernist, 2009, 25 MB PDF)",
                  "url": "https://www.usmodernist.org/2009newcanaan.pdf"},
    "distanceMi": mi(r["distance"]),
    "gainFt": round(r["elevation_gain"] * FT_PER_M),
    "terrain": r.get("terrain"), "difficulty": r.get("difficulty"),
    "surface": r.get("surface"), "type": r.get("track_type"),
    "start": {"lat": r["first_lat"], "lng": r["first_lng"], "name": "Irwin Park, Weed Street"},
    "houses": houses,
    "extras": extras,
    "finishCues": finish,
    "track": [[round(p["y"], 5), round(p["x"], 5), round(p.get("e", 0))] for p in track],
}

out = ("// Generated by scripts/build-route.py from Ride with GPS route "
       f"{ROUTE_ID}. Do not edit by hand.\nwindow.ROUTE = " + json.dumps(route, separators=(",", ":"), ensure_ascii=False) + ";\n")
(root / "data/route.js").write_text(out)

print(f"{route['name']}: {route['distanceMi']} mi, {route['gainFt']} ft, {len(track)} track points, {len(cues)} cues")
for o, h in sorted(houses.items()):
    print(f"{o:>2} mi {h['mile']:>5}  {h['visit'] or '-':8} {('at ' + h['stopAt']) if h['stopAt'] else '':16} off {h['offRouteM']:>3} m  cues {len(h['cuesIn'])}  {h['routeName']}")
for e in extras:
    print("extra:", e["name"], "|", e["note"])
